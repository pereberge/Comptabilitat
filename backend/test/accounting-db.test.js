import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import mysql from 'mysql2/promise';
import { config } from '../src/config.js';
import { createAccountingService } from '../src/services/accounting.js';
import { createContextService } from '../src/services/context.js';
import { createApp } from '../src/app.js';
test('MySQL: cuentas, asientos atómicos, aislamiento, concurrencia e idempotencia', {skip:process.env.TEST_MYSQL!=='1'},async()=>{
 const pool=mysql.createPool({...config.database,connectionLimit:8});
 let companyId,otherId;let server;
 try{
  const [company]=await pool.execute('INSERT INTO companies(name) VALUES (?)',['Prueba contable']);companyId=company.insertId;
  const [other]=await pool.execute('INSERT INTO companies(name) VALUES (?)',['Otra empresa']);otherId=other.insertId;
  const service=createAccountingService(pool,companyId),foreign=createAccountingService(pool,otherId);
  const make=async(code,parent_id=null,kind='account')=>service.createAccount({code,parent_id,description:'Cuenta '+code});
  const root=await make('4'),group=await make('43',root.id),account=await make('430',group.id);
  const g44=await make('44',root.id), a440=await make('440',g44.id), a4400=await make('4400',a440.id);
  assert.equal((await make('44000001',a4400.id,'subaccount')).parent_id,a4400.id);
  assert.equal((await service.nextCode(a440.id)).code,'44000002');
  const first=await make('43000001',account.id,'subaccount'),second=await make('43000002',account.id,'subaccount');
  assert.equal(first.kind,'subaccount');
  assert.equal(account.kind,'account');
  assert.equal((await service.nextCode(account.id)).code,'43000003');
  await assert.rejects(make('43000001',account.id,'subaccount'),e=>e.code==='ER_DUP_ENTRY');
  assert.equal((await make('4301',account.id)).parent_id,account.id);
  await assert.rejects(make('44',account.id),e=>e.code==='INVALID_PARENT');
  await assert.rejects(make('43000003',first.id,'subaccount'),e=>e.code==='INVALID_PARENT');
  await assert.rejects(foreign.getAccount(first.id),e=>e.code==='ACCOUNT_NOT_FOUND');
  await assert.rejects(service.updateAccount(first.id,{parent_id:first.id}),e=>e.code==='IMMUTABLE_ACCOUNT');
  assert.equal((await service.updateAccount(first.id,{description:'Cliente actualizado'})).description,'Cliente actualizado');
  assert.equal((await service.listAccounts({search:'actualizado'})).length,1);
  assert.equal((await service.listAccounts({kind:'subaccount'})).length,3);
  const [period]=await pool.execute("INSERT INTO accounting_exercises(company_id,name,start_date,end_date,status) VALUES (?,'2026','2026-01-01','2026-12-31','open')",[companyId]);
  const [closed]=await pool.execute("INSERT INTO accounting_exercises(company_id,name,start_date,end_date,status) VALUES (?,'2025','2025-01-01','2025-12-31','closed')",[companyId]);
  const [next]=await pool.execute("INSERT INTO accounting_exercises(company_id,name,start_date,end_date,status) VALUES (?,'2027','2027-01-01','2027-12-31','open')",[companyId]);
  const body=()=>({exercise_id:period.insertId,entry_date:'2026-10-15',description:'Operación',request_id:randomUUID(),lines:[{account_id:first.id,description:'Debe',debit:'0.30',credit:'0'},{account_id:second.id,description:'Haber',debit:'0',credit:'0.30'}]});
  await assert.rejects(service.createEntry({...body(),exercise_id:closed.insertId,entry_date:'2025-01-01'}),e=>e.code==='EXERCISE_CLOSED');
  await assert.rejects(service.createEntry({...body(),entry_date:'2027-01-01'}),e=>e.code==='DATE_OUTSIDE_EXERCISE');
  await assert.rejects(foreign.createEntry(body()),e=>e.code==='EXERCISE_NOT_FOUND');
  const invalid=body();invalid.lines[1].account_id=account.id;
  await assert.rejects(service.createEntry(invalid),e=>e.code==='SUBACCOUNT_REQUIRED');
  const missing=body();missing.lines[1].account_id=4294967295;
  await assert.rejects(service.createEntry(missing),e=>e.code==='ACCOUNT_NOT_FOUND');
  assert.equal((await service.listEntries({exercise_id:period.insertId})).length,0);
  const request=body(), saved=await service.createEntry(request);
  assert.equal(saved.number,1);
  assert.equal((await service.createEntry(request)).id,saved.id);
  await assert.rejects(service.createEntry({...request,description:'Cambio'}),e=>e.code==='REQUEST_CONFLICT');
  const concurrent=await Promise.all(Array.from({length:5},()=>service.createEntry(body())));
  assert.deepEqual(concurrent.map(e=>e.number).sort((a,b)=>a-b),[2,3,4,5,6]);
  const duplicate=body();const repeated=await Promise.all([service.createEntry(duplicate),service.createEntry(duplicate)]);
  assert.equal(repeated[0].id,repeated[1].id);
  assert.equal((await service.createEntry({...body(),exercise_id:next.insertId,entry_date:'2027-02-01'})).number,1);
  assert.equal((await service.getEntry(saved.id)).lines.length,2);
  await assert.rejects(foreign.getEntry(saved.id),e=>e.code==='ENTRY_NOT_FOUND');
  const journal=await service.listEntries({exercise_id:period.insertId,number:'1',view:'lines'});
  assert.equal(journal.length,2);
  assert.deepEqual(journal.map(l=>l.description),['Debe','Haber']);
  assert.equal(journal[0].account_code+journal[0].subaccount_code,first.code);
  assert.equal(journal[0].account_name,(await service.getAccount(first.id)).description);
  assert.equal(journal[0].debit,'0.30');
  assert.equal(journal[1].credit,'0.30');
  await assert.rejects(foreign.listEntries({exercise_id:period.insertId,view:'lines'}),e=>e.code==='EXERCISE_NOT_FOUND');
  assert.equal((await service.listEntries({exercise_id:period.insertId,from:'2026-11-01',view:'lines'})).length,0);
  assert.equal((await service.listEntries({exercise_id:period.insertId,number:'1'})).length,1);
  assert.equal((await service.listEntries({exercise_id:period.insertId,from:'2026-11-01'})).length,0);
  await assert.rejects(pool.execute('DELETE FROM accounts WHERE id=?',[first.id]));
  // Falla después de insertar la cabecera y la primera línea: la transacción debe revertir ambas.
  const failingPool={getConnection:async()=>{
   const db=await pool.getConnection();let lineCount=0;
   return {beginTransaction:()=>db.beginTransaction(),commit:()=>db.commit(),rollback:()=>db.rollback(),release:()=>db.release(),
    execute:async(sql,params)=>{if(sql.startsWith('INSERT INTO journal_lines')&&++lineCount===2)throw new Error('Injected failure');return db.execute(sql,params);}};
  }};
  await assert.rejects(createAccountingService(failingPool,companyId).createEntry(body()),/Injected failure/);
  assert.equal((await service.createEntry(body())).number,8);
  const [[counts]]=await pool.execute('SELECT COUNT(*) AS total FROM journal_lines WHERE company_id=?',[companyId]);
  assert.equal(counts.total,18);
  server=createApp(createContextService(pool,companyId),service).listen(0,'127.0.0.1');
  await new Promise(resolve=>server.once('listening',resolve));
  const base='http://127.0.0.1:'+server.address().port;
  const response=await fetch(base+'/api/entries',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body())});
  assert.equal(response.status,201);
  const list=await fetch(base+'/api/entries?exercise_id='+period.insertId);
  assert.equal(list.status,200);assert.equal((await list.json()).length,9);
  const dotted=await service.createAccount({code:'4300.0003',description:'Dotted customer'});
  assert.equal(dotted.code,'43000003');assert.equal(dotted.parent_code,'4300');
  assert.equal((await service.getAccount(dotted.parent_id)).description,'Clientes (euros)');
  assert.equal((await service.getAccount(first.id)).parent_id,account.id);
  await assert.rejects(service.createAccount({code:'43000003',description:'Duplicate'}),e=>e.code==='ER_DUP_ENTRY');
  const customSub=await service.createAccount({code:'4398.0001',description:'Custom customer'});
  assert.equal(customSub.parent_code,'4398');
  assert.equal((await service.getAccount(customSub.parent_id)).description,'Cuenta 4398');
  const hierarchy=await service.listAccounts();assert.ok(hierarchy.find(a=>a.code==='439'));
  await assert.rejects(service.createAccount({code:'4388.01',description:'Bad length'}),e=>e.code==='INVALID_SUBACCOUNT_FORMAT');
  assert.ok(!(await service.listAccounts()).some(a=>a.code==='4388'));
  const paired=await Promise.all([service.createAccount({code:'4370.0001',description:'One'}),service.createAccount({code:'4370.0002',description:'Two'})]);
  assert.equal(paired[0].parent_id,paired[1].parent_id);
  const straight=await service.createAccount({code:'4360',description:'Custom account'});
  assert.equal(straight.kind,'account');assert.equal(straight.parent_code,'436');
 }finally{
  if(server)await new Promise(resolve=>server.close(resolve));
  if(companyId){
   await pool.execute('DELETE FROM journal_lines WHERE company_id=?',[companyId]);
   await pool.execute('DELETE FROM journal_entries WHERE company_id=?',[companyId]);
   await pool.execute('DELETE FROM accounting_exercises WHERE company_id=?',[companyId]);
   const [rows]=await pool.execute('SELECT id FROM accounts WHERE company_id=? ORDER BY LENGTH(code) DESC',[companyId]);
   for(const row of rows)await pool.execute('DELETE FROM accounts WHERE id=?',[row.id]);
   await pool.execute('DELETE FROM companies WHERE id=?',[companyId]);
  }
  if(otherId)await pool.execute('DELETE FROM companies WHERE id=?',[otherId]);
  await pool.end();
 }
});
