CREATE TABLE IF NOT EXISTS farm_sales (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 company_id INT UNSIGNED NOT NULL,
 exercise_id INT UNSIGNED NOT NULL,
 lot_id INT UNSIGNED NOT NULL,
 sale_date DATE NOT NULL,
 pigs INT UNSIGNED NOT NULL,
 kg_per_pig DECIMAL(10,3) NOT NULL,
 price_per_kg DECIMAL(13,5) NOT NULL,
 total_kg DECIMAL(18,3) NOT NULL,
 total_amount DECIMAL(15,2) NOT NULL,
 notes VARCHAR(2000) NOT NULL DEFAULT '',
 request_id CHAR(36) CHARACTER SET ascii NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 voided TINYINT UNSIGNED NOT NULL DEFAULT 0,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_farm_sale_request(company_id,request_id),
 INDEX idx_farm_sale_scope(company_id,exercise_id,lot_id,sale_date),
 FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,exercise_id) REFERENCES accounting_exercises(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,lot_id) REFERENCES farm_lots(company_id,id) ON DELETE RESTRICT,
 CHECK(pigs>0 AND pigs<=10000000),
 CHECK(kg_per_pig>0 AND kg_per_pig<=9999.999),
 CHECK(price_per_kg>0 AND price_per_kg<=999999.99999),
 CHECK(total_kg>0 AND total_amount>=0),
 CHECK(voided IN (0,1))
) ENGINE=InnoDB;
