CREATE TABLE IF NOT EXISTS invoice_documents (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 company_id INT UNSIGNED NOT NULL,
 exercise_id INT UNSIGNED NOT NULL,
 source_name VARCHAR(255) NOT NULL,
 source_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 source_pdf MEDIUMBLOB NOT NULL,
 pages SMALLINT UNSIGNED NOT NULL,
 extraction JSON NOT NULL,
 form JSON NOT NULL,
 proposal JSON NOT NULL,
 direction ENUM('issued','received') NOT NULL DEFAULT 'received',
 reference VARCHAR(60) NOT NULL DEFAULT '',
 party_name VARCHAR(200) NOT NULL DEFAULT '',
 party_tax_id VARCHAR(32) NOT NULL DEFAULT '',
 invoice_date DATE NULL,
 total_amount DECIMAL(15,2) NULL,
 status ENUM('draft','posted','linked') NOT NULL DEFAULT 'draft',
 invoice_id INT UNSIGNED NULL,
 entry_id INT UNSIGNED NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_invoice_document_source(company_id,exercise_id,source_sha256),
 FOREIGN KEY(company_id,exercise_id) REFERENCES accounting_exercises(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,invoice_id) REFERENCES trade_invoices(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,entry_id) REFERENCES journal_entries(company_id,id) ON DELETE RESTRICT,
 INDEX idx_invoice_document_scope(company_id,exercise_id,invoice_date)
) ENGINE=InnoDB
