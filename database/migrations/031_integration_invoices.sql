CREATE TABLE integration_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 request_id CHAR(36) CHARACTER SET ascii NOT NULL,
 client_id VARCHAR(64) CHARACTER SET ascii NULL,
 company_id INT UNSIGNED NULL,
 integration_invoice_id INT UNSIGNED NULL,
 actor VARCHAR(64) NOT NULL,
 action VARCHAR(60) CHARACTER SET ascii NOT NULL,
 http_status SMALLINT UNSIGNED NULL,
 error_code VARCHAR(100) CHARACTER SET ascii NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_integration_event_company(company_id,created_at),
 INDEX idx_integration_event_request(request_id)
) ENGINE=InnoDB;
