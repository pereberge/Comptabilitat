CREATE TABLE IF NOT EXISTS integration_company_links (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 client_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_system VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 external_company_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 company_id INT UNSIGNED NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_integration_company(client_id,source_system,external_company_id),
 FOREIGN KEY(company_id) REFERENCES companies(id)
) ENGINE=InnoDB;
