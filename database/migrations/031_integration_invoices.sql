CREATE TABLE integration_received_invoices (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 company_id INT UNSIGNED NOT NULL,
 exercise_id INT UNSIGNED NULL,
 client_id VARCHAR(64) CHARACTER SET ascii NOT NULL,
 source_system VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 external_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 payload_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 payload JSON NOT NULL,
 supplier_name VARCHAR(200) NOT NULL,
 supplier_tax_id VARCHAR(32) CHARACTER SET ascii NOT NULL,
 supplier_account_id INT UNSIGNED NULL,
 invoice_number VARCHAR(60) NOT NULL,
 fiscal_number VARCHAR(60) COLLATE utf8mb4_0900_ai_ci NOT NULL,
 invoice_date DATE NOT NULL,
 due_date DATE NOT NULL,
 currency CHAR(3) CHARACTER SET ascii NOT NULL,
 invoice_type ENUM('standard','credit_note','rectifying') NOT NULL,
 base_total DECIMAL(15,2) NOT NULL,
 tax_total DECIMAL(15,2) NOT NULL,
 withholding_total DECIMAL(15,2) NOT NULL,
 total_amount DECIMAL(15,2) NOT NULL,
 document_external_id VARCHAR(200) NOT NULL,
 status ENUM('pending','posted','issues','cancelled','rectified') NOT NULL DEFAULT 'pending',
 possible_duplicate BOOLEAN NOT NULL DEFAULT FALSE,
 issues JSON NOT NULL,
 invoice_id INT UNSIGNED NULL,
 entry_id INT UNSIGNED NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 imported_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_integration_invoice(company_id,source_system,external_id),
 INDEX idx_integration_fiscal(company_id,supplier_tax_id,fiscal_number),
 INDEX idx_integration_invoice_list(company_id,invoice_date,id),
 FOREIGN KEY(company_id) REFERENCES companies(id),
 FOREIGN KEY(company_id,exercise_id) REFERENCES accounting_exercises(company_id,id),
 FOREIGN KEY(company_id,supplier_account_id) REFERENCES accounts(company_id,id),
 FOREIGN KEY(invoice_id) REFERENCES trade_invoices(id) ON DELETE SET NULL,
 FOREIGN KEY(entry_id) REFERENCES journal_entries(id) ON DELETE SET NULL
) ENGINE=InnoDB;
