CREATE TABLE IF NOT EXISTS trade_invoices (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 company_id INT UNSIGNED NOT NULL,
 exercise_id INT UNSIGNED NOT NULL,
 direction ENUM('issued','received') NOT NULL,
 reference VARCHAR(60) NOT NULL,
 invoice_date DATE NOT NULL,
 posting_date DATE NOT NULL,
 party_name VARCHAR(200) NOT NULL,
 party_tax_id VARCHAR(32) NOT NULL DEFAULT '',
 party_address VARCHAR(250) NOT NULL DEFAULT '',
 party_email VARCHAR(254) NOT NULL DEFAULT '',
 party_account_id INT UNSIGNED NOT NULL,
 offset_account_id INT UNSIGNED NOT NULL,
 vat_account_id INT UNSIGNED NULL,
 withholding_account_id INT UNSIGNED NULL,
 issuer_snapshot JSON NOT NULL,
 base_total DECIMAL(15,2) NOT NULL,
 tax_total DECIMAL(15,2) NOT NULL,
 withholding_rate DECIMAL(5,2) NOT NULL DEFAULT 0,
 withholding_total DECIMAL(15,2) NOT NULL DEFAULT 0,
 total_amount DECIMAL(15,2) NOT NULL,
 payment_method ENUM('transfer','direct_debit','cash','card','other') NOT NULL DEFAULT 'transfer',
 notes VARCHAR(1000) NOT NULL DEFAULT '',
 status ENUM('posted','void') NOT NULL DEFAULT 'posted',
 entry_id INT UNSIGNED NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 reference_party_id INT UNSIGNED GENERATED ALWAYS AS (IF(direction='issued',0,party_account_id)) STORED,
 void_entry_id INT UNSIGNED NULL,
 void_request_id CHAR(36) CHARACTER SET ascii NULL,
 void_request_hash CHAR(64) CHARACTER SET ascii NULL,
 void_date DATE NULL,
 void_reason VARCHAR(200) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_invoice_scope(company_id,id),
 UNIQUE KEY uq_invoice_reference(company_id,direction,reference,reference_party_id),
 UNIQUE KEY uq_invoice_entry(company_id,entry_id),
 UNIQUE KEY uq_invoice_request(company_id,request_id),
 FOREIGN KEY(company_id,exercise_id) REFERENCES accounting_exercises(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,party_account_id) REFERENCES accounts(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,offset_account_id) REFERENCES accounts(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,vat_account_id) REFERENCES accounts(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,withholding_account_id) REFERENCES accounts(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,entry_id) REFERENCES journal_entries(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,void_entry_id) REFERENCES journal_entries(company_id,id) ON DELETE RESTRICT,
 CHECK(total_amount>0 AND base_total>0 AND tax_total>=0 AND withholding_total>=0 AND total_amount=base_total+tax_total-withholding_total),
 CHECK(withholding_rate>=0 AND withholding_rate<=100),
 CHECK(posting_date>=invoice_date),
 INDEX idx_invoice_date(company_id,exercise_id,invoice_date)
) ENGINE=InnoDB
-- statement
CREATE TABLE IF NOT EXISTS trade_invoice_lines (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 company_id INT UNSIGNED NOT NULL,
 invoice_id INT UNSIGNED NOT NULL,
 position SMALLINT UNSIGNED NOT NULL,
 description VARCHAR(200) NOT NULL,
 base DECIMAL(15,2) NOT NULL,
 tax_rate DECIMAL(5,2) NOT NULL,
 tax_amount DECIMAL(15,2) NOT NULL,
 UNIQUE KEY uq_invoice_line(invoice_id,position),
 FOREIGN KEY(company_id,invoice_id) REFERENCES trade_invoices(company_id,id) ON DELETE RESTRICT,
 CHECK(base>0 AND tax_amount>=0 AND tax_rate>=0 AND tax_rate<=100)
) ENGINE=InnoDB
-- statement
CREATE TABLE IF NOT EXISTS portfolio_receipts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 company_id INT UNSIGNED NOT NULL,
 invoice_id INT UNSIGNED NOT NULL,
 position SMALLINT UNSIGNED NOT NULL,
 original_due_date DATE NOT NULL,
 due_date DATE NOT NULL,
 amount DECIMAL(15,2) NOT NULL,
 payment_method ENUM('transfer','direct_debit','cash','card','other') NOT NULL,
 notes VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_receipt_scope(company_id,id),
 UNIQUE KEY uq_invoice_receipt(invoice_id,position),
 FOREIGN KEY(company_id,invoice_id) REFERENCES trade_invoices(company_id,id) ON DELETE RESTRICT,
 CHECK(amount>0),
 INDEX idx_receipt_due(company_id,due_date)
) ENGINE=InnoDB
-- statement
CREATE TABLE IF NOT EXISTS portfolio_settlements (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 company_id INT UNSIGNED NOT NULL,
 receipt_id INT UNSIGNED NOT NULL,
 exercise_id INT UNSIGNED NOT NULL,
 payment_date DATE NOT NULL,
 amount DECIMAL(15,2) NOT NULL,
 bank_account_id INT UNSIGNED NOT NULL,
 payment_method ENUM('transfer','direct_debit','cash','card','other') NOT NULL,
 reference VARCHAR(100) NOT NULL DEFAULT '',
 notes VARCHAR(500) NOT NULL DEFAULT '',
 entry_id INT UNSIGNED NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 reversal_entry_id INT UNSIGNED NULL,
 reversal_request_id CHAR(36) CHARACTER SET ascii NULL,
 reversal_request_hash CHAR(64) CHARACTER SET ascii NULL,
 reversal_date DATE NULL,
 reversal_reason VARCHAR(200) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_settlement_scope(company_id,id),
 UNIQUE KEY uq_settlement_request(company_id,request_id),
 UNIQUE KEY uq_settlement_entry(company_id,entry_id),
 FOREIGN KEY(company_id,receipt_id) REFERENCES portfolio_receipts(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,exercise_id) REFERENCES accounting_exercises(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,bank_account_id) REFERENCES accounts(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,entry_id) REFERENCES journal_entries(company_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(company_id,reversal_entry_id) REFERENCES journal_entries(company_id,id) ON DELETE RESTRICT,
 CHECK(amount>0),
 INDEX idx_settlement_receipt(company_id,receipt_id)
) ENGINE=InnoDB
