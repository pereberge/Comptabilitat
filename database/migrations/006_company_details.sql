CREATE TABLE IF NOT EXISTS company_details (
  company_id INT UNSIGNED PRIMARY KEY,
  tax_id VARCHAR(32) NOT NULL DEFAULT '',
  trade_name VARCHAR(160) NOT NULL DEFAULT '',
  address VARCHAR(250) NOT NULL DEFAULT '',
  postal_code VARCHAR(20) NOT NULL DEFAULT '',
  city VARCHAR(100) NOT NULL DEFAULT '',
  province VARCHAR(100) NOT NULL DEFAULT '',
  country VARCHAR(100) NOT NULL DEFAULT '',
  contact_person VARCHAR(160) NOT NULL DEFAULT '',
  phone VARCHAR(40) NOT NULL DEFAULT '',
  email VARCHAR(254) NOT NULL DEFAULT '',
  billing_email VARCHAR(254) NOT NULL DEFAULT '',
  website VARCHAR(254) NOT NULL DEFAULT '',
  bank_name VARCHAR(120) NOT NULL DEFAULT '',
  account_holder VARCHAR(160) NOT NULL DEFAULT '',
  iban VARCHAR(34) CHARACTER SET ascii NOT NULL DEFAULT '',
  bic VARCHAR(11) CHARACTER SET ascii NOT NULL DEFAULT '',
  payment_method ENUM('', 'transfer', 'direct_debit', 'cash', 'card', 'other') NOT NULL DEFAULT '',
  payment_terms VARCHAR(160) NOT NULL DEFAULT '',
  invoice_notes VARCHAR(1000) NOT NULL DEFAULT '',
  registry_info VARCHAR(500) NOT NULL DEFAULT '',
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_company_details FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
  INDEX idx_company_tax_id (tax_id)
) ENGINE=InnoDB
