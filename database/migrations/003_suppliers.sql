CREATE TABLE IF NOT EXISTS suppliers (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  company_id INT UNSIGNED NOT NULL,
  code INT UNSIGNED NOT NULL,
  trade_name VARCHAR(200) NOT NULL DEFAULT '',
  legal_name VARCHAR(200) NOT NULL,
  tax_id VARCHAR(32) NOT NULL DEFAULT '',
  address VARCHAR(250) NOT NULL DEFAULT '',
  postal_code VARCHAR(20) NOT NULL DEFAULT '',
  city VARCHAR(100) NOT NULL DEFAULT '',
  province VARCHAR(100) NOT NULL DEFAULT '',
  country VARCHAR(100) NOT NULL DEFAULT '',
  phone VARCHAR(40) NOT NULL DEFAULT '',
  email VARCHAR(254) NOT NULL DEFAULT '',
  contact_person VARCHAR(200) NOT NULL DEFAULT '',
  notes VARCHAR(2000) NOT NULL DEFAULT '',
  payment_terms VARCHAR(100) NOT NULL DEFAULT '',
  iban VARCHAR(34) CHARACTER SET ascii NOT NULL DEFAULT '',
  vat_rate DECIMAL(5,2) NULL,
  account_id INT UNSIGNED NOT NULL,
  status ENUM('active','inactive') NOT NULL DEFAULT 'active',
  request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT uq_supplier_code UNIQUE(company_id, code),
  CONSTRAINT uq_supplier_account UNIQUE(company_id, account_id),
  CONSTRAINT uq_supplier_request UNIQUE(company_id, request_id),
  CONSTRAINT fk_supplier_company FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE RESTRICT,
  CONSTRAINT fk_supplier_account FOREIGN KEY(company_id, account_id) REFERENCES accounts(company_id, id) ON DELETE RESTRICT,
  CONSTRAINT chk_supplier_name CHECK(CHAR_LENGTH(TRIM(legal_name)) > 0),
  CONSTRAINT chk_supplier_code CHECK(code > 0),
  CONSTRAINT chk_supplier_vat CHECK(vat_rate IS NULL OR (vat_rate >= 0 AND vat_rate <= 100)),
  INDEX idx_supplier_name(company_id, legal_name),
  INDEX idx_supplier_tax(company_id, tax_id),
  INDEX idx_supplier_status(company_id, status)
) ENGINE=InnoDB
